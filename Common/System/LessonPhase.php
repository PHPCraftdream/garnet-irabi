<?php declare(strict_types=1);

namespace PHPCraftdream\IRabi\Common\System {
    /**
     * Фаза занятия — где оно стоит относительно «сейчас».
     *
     * Здесь и только здесь живут числа, задающие границы фаз: сроки
     * напоминаний и их нижние границы. До этого они были размазаны — окна в
     * `CronReminderService`, граница завершения литералом в трёх запросах
     * `CronCompletionService`, — и всякий, кому нужно было «то же самое
     * условие», переписывал его у себя. Два таких списка неизбежно
     * разъезжаются, причём молча: крон продолжает работать по своим числам,
     * инструмент рапортует по своим, и расхождение видно только когда письмо
     * не пришло.
     *
     * Крон читает сроки отсюда. Инструмент сдвига считает отсюда же якоря.
     * Расхождения нет по построению, а не по договорённости.
     */
    enum LessonPhase: string {
        /** Далёкое будущее: до занятия больше суток, напоминаний ещё не было. */
        case Far = 'far';

        /** Окно суточного напоминания. */
        case DayBefore = '1d-before';

        /** Окно двухчасового напоминания. */
        case HoursBefore = '2h-before';

        /** Занятие идёт: началось, но ещё не кончилось. */
        case Running = 'running';

        /** Занятие прошло: крон вправе его завершить. */
        case Past = 'past';

        /**
         * Сроки напоминаний: за сколько до начала и как называется отметка.
         *
         * Порядок важен — от дальнего к ближнему: фаза определяется первым
         * подошедшим сроком, и для занятия через час подойти должен
         * двухчасовой, а не суточный.
         *
         * @var array<string, array{column: string, seconds: int}>
         */
        public const LEADS = [
            '1d' => ['column' => 'reminded_1d_at', 'seconds' => 86400],
            '2h' => ['column' => 'reminded_2h_at', 'seconds' => 7200],
        ];

        /**
         * Нижняя граница окна: раньше этого срока до начала напоминание уже
         * не отправляют.
         *
         * Крон может не отработать вовремя — хост лежал, задача упала, — и
         * тогда занятие окажется ближе, чем срок напоминания. Суточное за
         * десять минут до начала бессмысленно и выглядит поломкой, поэтому
         * оно отправляется, пока до занятия больше двух часов. Двухчасовое —
         * пока занятие не началось.
         *
         * @var array<string, int>
         */
        public const FLOOR = ['1d' => 7200, '2h' => 0];

        /**
         * Запас, на который якорь отступает от края окна.
         *
         * Ставить занятие ровно на границу нельзя: там `<` и `<=` становятся
         * деталью реализации, а тестировщик не должен от неё зависеть. Пять
         * минут многократно перекрывают разницу между «сейчас» инструмента и
         * «сейчас» крона — они считаются в одном процессе и расходятся на
         * миллисекунды.
         */
        public const ANCHOR_MARGIN_SEC = 300;

        /** На сколько занятие заводится вперёд для фазы «далёкое будущее». */
        public const FAR_AHEAD_SEC = 7 * 86400;

        /** На сколько конец занятия отводится назад для фазы «прошло». */
        public const PAST_BEHIND_SEC = 3600;

        /** Где стоит занятие с такими метками. */
        public static function of(int $startAt, int $endAt, int $now): self {
            if ($endAt <= $now) {
                return self::Past;
            }

            if ($startAt <= $now) {
                return self::Running;
            }

            // От ближнего срока к дальнему: занятие через час попадает в
            // двухчасовое окно, а не в суточное.
            foreach (array_reverse(self::LEADS, true) as $lead => $cfg) {
                $untilStart = $startAt - $now;

                if ($untilStart > self::FLOOR[$lead] && $untilStart <= $cfg['seconds']) {
                    return $lead === '1d' ? self::DayBefore : self::HoursBefore;
                }
            }

            return self::Far;
        }

        /**
         * Куда поставить начало занятия, чтобы оно оказалось в этой фазе.
         *
         * Все якоря — строго внутри окна, а не на его краю. Для окон
         * напоминаний берётся дальний край: там до следующей границы остаётся
         * почти всё окно, и у проверяющего есть время посмотреть на результат,
         * прежде чем занятие переползёт в следующую фазу.
         *
         * @param int $durationSec длительность занятия; нужна только «идёт» и
         *                         «прошло», остальным фазам безразлична
         */
        public function anchorStart(int $now, int $durationSec): int {
            return match ($this) {
                self::Far => $now + self::FAR_AHEAD_SEC,
                self::DayBefore => $now + self::LEADS['1d']['seconds'] - self::ANCHOR_MARGIN_SEC,
                self::HoursBefore => $now + self::LEADS['2h']['seconds'] - self::ANCHOR_MARGIN_SEC,
                // Середина занятия: одинаково далеко от обеих границ, так что
                // короткое занятие не проскочит фазу за время проверки.
                self::Running => $now - intdiv($durationSec, 2),
                // Считаем от конца: «прошло» задаётся `end_at`, а не началом.
                self::Past => $now - self::PAST_BEHIND_SEC - $durationSec,
            };
        }

        /**
         * Надо ли снимать отметку об отправленном напоминании при переезде в
         * эту фазу.
         *
         * Снимаем ровно тогда, когда окно этого срока ещё впереди: занятие в
         * своей новой фазе честно «не получало» такого письма. Для фазы
         * «идёт» и «прошло» отметки остаются — это история, и стирать её
         * значит терять ответ на вопрос «суточное уже отправляли?».
         */
        public function resetsMark(string $lead, int $newStartAt, int $now): bool {
            return $newStartAt > $now + self::FLOOR[$lead];
        }

        /** Человеку — перечень имён, которые вообще принимаются. */
        public static function names(): array {
            return array_map(static fn (self $c): string => $c->value, self::cases());
        }
    }
}
