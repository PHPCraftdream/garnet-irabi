/**
 * Перед первым POST теста вернуть анти-бот куку хоста.
 *
 * Прод стоит за защитой, которая на POST без куки отвечает страницей с
 * мета-редиректом и `Set-Cookie: RCPC=…`. Формально это HTTP 200, но
 * приложение запроса не видит.
 *
 * Для `page.goto` это незаметно — браузер идёт по редиректу. Для
 * `page.request.post(...)` и для `fetch()` из страницы — нет: проверка видит
 * 200 от страницы-барьера, а тело POST теряется. Именно так проверки прав
 * читались как провалы: `expect(403)` получал `200`, будто модератору
 * разрешили двигать деньги, а владельцу — выдавать права владельца. Замер
 * показал обратное: запрос до приложения не доходил, проводок не
 * создавалось, флаг не выставлялся. Ломался сигнал, а не продукт — и это
 * опаснее обычного падения, потому что файлы проверок прав идут
 * последовательно: одно такое падение снимало с прогона все остальные
 * проверки и оставляло нас без данных там, где мы считали, что всё зелено.
 *
 * Прогрев обязан быть POST-ом: GET не челленджится и куки не приносит.
 * `/admin/` выбран намеренно — он отвечает барьеру и ничего не делает.
 *
 * Вызывать после КАЖДОГО сброса кук (`clearCookies`), в том числе внутри
 * входа под роль. Намеренно best-effort: локальный прогон такой защиты не
 * имеет, и падение здесь не должно ронять тест.
 */
import type { BrowserContext } from '@playwright/test';
import { isProd } from './ssh-bridge';

export async function warmAntiBotCookie(ctx: BrowserContext): Promise<void> {
    if (!isProd()) {
        return;
    }

    try {
        await ctx.request.post('/admin/', { data: '', timeout: 10000, failOnStatusCode: false });
    } catch {
        // Хост недоступен или медленный — настоящую причину покажет сам тест.
    }
}
