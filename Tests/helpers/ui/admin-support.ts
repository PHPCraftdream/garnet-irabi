/**
 * Прийти в очередь обращений так, как её видит модератор, только что
 * открывший раздел.
 *
 * AdminSupportIsland намеренно запоминает открытые вкладки тикетов в
 * `sessionStorage['admin-support-open-tickets']` и после перезагрузки снова
 * делает активной вкладку тикета: модератор посреди разбора не должен заново
 * искать обращение в очереди. Побочное следствие для проверок — после
 * `goto('/admin/support/')` на экране может оказаться НЕ очередь, а
 * последний открытый тикет, и клик по строке `support-ticket-N` ждёт до
 * таймаута, потому что списка в DOM нет.
 *
 * Так падали три проверки (admin-moderates-support шаг 8,
 * support-concurrent-reply-notice, support-stale-reply-warning): контекст
 * роли живёт дольше одного файла, и вкладка, открытая предыдущей проверкой,
 * восстанавливалась в следующей. Продукт при этом вёл себя как задумано —
 * ломались именно проверки, причём молча: падение выглядело как «тикета нет
 * в очереди».
 *
 * Поэтому проверки, которым нужна именно очередь, приходят сюда: ключ
 * очищается, страница перезагружается, на экране гарантированно список.
 */
import type { Page } from '@playwright/test';

export const OPEN_TICKETS_KEY = 'admin-support-open-tickets';

/** Открыть раздел обращений с гарантированно активной вкладкой очереди. */
export async function openAdminSupportQueue(page: Page): Promise<void> {
    await page.goto('/admin/support/');
    await page.evaluate((key: string) => {
        try {
            sessionStorage.removeItem(key);
        } catch { /* хранилище недоступно — значит и восстанавливать нечего */ }
    }, OPEN_TICKETS_KEY);
    await page.reload();
}

/**
 * Открыть конкретное обращение.
 *
 * Через deep-link `#ticket=<id>`, а не кликом по очереди, и это не
 * срезание угла: очередь пагинирована по 10 строк и отсортирована по
 * времени обновления, поэтому под полным прогоном наш тикет закономерно
 * уходит со первой страницы — соседние проверки создают свои, более
 * свежие. Клик по строке тогда ждёт до таймаута, и выглядит это как
 * «тикета нет», хотя он есть и открывается.
 *
 * Именно так живой человек и приходит в обращение из письма-уведомления;
 * остров этот путь поддерживает специально, включая случай, когда тикет
 * вообще не попал в загруженный список (тогда вкладка открывается с
 * заглушкой вместо темы, а тему дозапрашивает сама).
 */
export async function openAdminTicket(page: Page, ticketId: number): Promise<void> {
    // Чистить сохранённые вкладки здесь не нужно и нельзя: путь с хешем в
    // острове обрабатывается ДО чтения sessionStorage и сразу выходит, а
    // очистка через addInitScript осталась бы на все последующие переходы
    // этой страницы — в том числе на перезагрузку, которую отдельная
    // проверка как раз и проверяет.
    await page.goto(`/admin/support/#ticket=${ticketId}`);
}

/**
 * Найти обращение в очереди по теме и открыть его кликом.
 *
 * Для проверок, чьё утверждение — «тикет ВИДЕН в очереди»: там deep-link
 * не годится, он доказывал бы другое. Поиск по теме снимает зависимость от
 * страницы пагинации, не подменяя предмет проверки.
 */
export async function openAdminTicketFromQueue(page: Page, ticketId: number, subject: string): Promise<void> {
    await openAdminSupportQueue(page);
    await page.locator('[data-test-id="admin-grid-search"]').fill(subject);
    await page.locator(`[data-test-id="support-ticket-${ticketId}"]`).click();
}
